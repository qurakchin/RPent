"""Requirements rendering is stable and hashes cover every install input."""

import pytest

from rpent.install.errors import InstallConfigError
from rpent.install.requirements import (
    INPUT_SCHEMA,
    installed_dependencies,
    read_core_dependencies,
    render_requirements,
    requirements_inputs,
    requirements_sha256,
)
from rpent.install.resolve import resolve


@pytest.fixture
def resolution(make_component, make_catalog):
    robot = make_component(
        "robot-alpha",
        dependencies=["numpy>=2", "torch==2.7.0"],
    )
    model = make_component(
        "model-molmo",
        dependencies=["transformers>=4.57"],
    )
    catalog = make_catalog(components=[robot, model])
    return resolve(("robot-alpha", "model-molmo"), catalog)


def test_render_requirements_groups_core_and_components(resolution):
    text = render_requirements(resolution, core_dependencies=("packaging", "PyYAML"))

    assert text.splitlines()[:4] == [
        "# Generated by rpent-install from the component manifests.",
        "# Do not edit; change a component manifest and rerun",
        "# `rpent-install install robot-alpha model-molmo`.",
        "# environment: model-molmo+robot-alpha",
    ]
    assert "# RPent core\nPyYAML\npackaging" in text
    assert "# component robot-alpha" in text
    assert text.index("numpy>=2") < text.index("torch==2.7.0")


def test_the_minimal_environment_renders_core_only(make_catalog):
    resolution = resolve((), make_catalog())

    text = render_requirements(resolution, core_dependencies=("packaging",))

    assert "# `rpent-install install (no components)`." in text
    assert "# environment: minimal" in text
    assert text.rstrip().endswith("packaging")
    assert "# component" not in text


def test_a_selected_model_renders_its_own_packages(resolution):
    text = render_requirements(resolution, core_dependencies=("packaging",))

    assert "# component model-molmo" in text
    assert "transformers>=4.57" in text


def test_installed_dependencies_include_core_and_every_component(resolution):
    assert installed_dependencies(resolution, core_dependencies=("packaging",)) == (
        "packaging",
        "numpy>=2",
        "torch==2.7.0",
        "transformers>=4.57",
    )


def test_requirements_hash_tracks_manifests_and_options(resolution, tmp_path):
    baseline = requirements_sha256(
        resolution, root=tmp_path, core_dependencies=("packaging",)
    )

    assert baseline == requirements_sha256(
        resolution, root=tmp_path, core_dependencies=("packaging",)
    )
    assert baseline != requirements_sha256(
        resolution, root=tmp_path, core_dependencies=("packaging", "pytest")
    )

    inputs = requirements_inputs(
        resolution, root=tmp_path, core_dependencies=("packaging",)
    )
    assert inputs["schema"] == INPUT_SCHEMA
    assert inputs["environment"]["components"]["robot-alpha"] == {
        "manifest_sha256": "robot-alpha"
    }
    assert inputs["environment"]["python"] == "3.12"
    assert inputs["environment"]["platform"] == "linux-x86_64"
    assert inputs["environment"]["manylinux"] == "2_31"
    assert inputs["core_dependencies"] == ["packaging"]


def test_requirements_hash_does_not_depend_on_the_environment_name(
    make_component, make_catalog, tmp_path
):
    # Two requests that resolve to the same closure install the same packages,
    # so the name they form is not an installation input.
    alpha = make_component("robot-alpha")
    catalog = make_catalog([alpha])

    named = resolve(("robot-alpha",), catalog)
    other = resolve(("robot-alpha", "robot-alpha"), catalog)

    assert named.name == other.name
    assert requirements_sha256(named, root=tmp_path) == requirements_sha256(
        other, root=tmp_path
    )


def test_requirements_hash_tracks_the_manylinux_baseline(
    make_component, make_catalog, tmp_path
):
    default_robot = make_component("robot-alpha")
    raised_robot = make_component("robot-beta", manylinux="2_35")
    default = resolve(("robot-alpha",), make_catalog([default_robot]))
    raised = resolve(("robot-beta",), make_catalog([raised_robot]))

    # The baseline decides which wheel tags uv may select, so it is an input
    # even though it does not appear in the rendered requirements.
    assert requirements_sha256(default, root=tmp_path) != requirements_sha256(
        raised, root=tmp_path
    )
    assert (
        requirements_inputs(raised, root=tmp_path)["environment"]["manylinux"] == "2_35"
    )


def test_requirements_inputs_record_components(make_component, make_catalog, tmp_path):
    rlinf = make_component("infra-rlinf")
    alpha = make_component("robot-alpha", requires=["infra-rlinf"])
    catalog = make_catalog([rlinf, alpha])

    resolution = resolve(("robot-alpha",), catalog)

    inputs = requirements_inputs(resolution, root=tmp_path)
    # A component entry records only what decides the environment's contents.
    assert set(inputs["environment"]["components"]["infra-rlinf"]) == {
        "manifest_sha256"
    }


def test_requirements_hash_ignores_a_checked_in_lock(
    make_component, make_catalog, tmp_path, write_toml
):
    # Locks are reproduction artifacts, not installation inputs: rewriting or
    # deleting one cannot change what a reinstall produces.
    robot = make_component("robot-alpha", dependencies=["numpy>=2"])
    resolution = resolve(("robot-alpha",), make_catalog([robot]))
    lock = write_toml("tests/locks/robot-alpha.lock", "numpy==2.0.0")

    baseline = requirements_sha256(resolution, root=tmp_path)
    inputs = requirements_inputs(resolution, root=tmp_path)
    assert "lock_sha256" not in inputs

    lock.write_text("numpy==2.1.0\n", encoding="utf-8")
    assert baseline == requirements_sha256(resolution, root=tmp_path)

    lock.unlink()
    assert baseline == requirements_sha256(resolution, root=tmp_path)


def test_requirements_hash_tracks_component_overrides(
    make_component, make_catalog, tmp_path, write_toml
):
    declared = "robots/alpha/requirements/override.txt"
    # Manifests resolve overrides to absolute paths when they are loaded.
    override = write_toml(declared, "numpy<2")
    robot = make_component(
        "robot-alpha", dependencies=["numpy>=2"], overrides=[override]
    )
    resolution = resolve(("robot-alpha",), make_catalog([robot]))

    baseline = requirements_sha256(resolution, root=tmp_path)
    inputs = requirements_inputs(resolution, root=tmp_path)
    assert [entry["path"] for entry in inputs["overrides"]] == [str(declared)]

    override.write_text("numpy<3\n", encoding="utf-8")
    changed = requirements_sha256(resolution, root=tmp_path)
    assert baseline != changed

    # Files the installation never reads are not inputs.
    write_toml("robots/alpha/README.md", "notes")
    assert changed == requirements_sha256(resolution, root=tmp_path)


def test_requirement_file_hashes_ignore_comments_and_blank_lines(
    make_component, make_catalog, tmp_path, write_toml
):
    override = write_toml("robots/alpha/requirements/override.txt", "numpy<2")
    robot = make_component(
        "robot-alpha", dependencies=["numpy>=2"], overrides=[override]
    )
    resolution = resolve(("robot-alpha",), make_catalog([robot]))

    baseline = requirements_sha256(resolution, root=tmp_path)

    # uv ignores comments and blank lines, so editing them cannot change what
    # a reinstall produces.
    override.write_text("# pinned for the simulator stack\nnumpy<2\n")
    assert baseline == requirements_sha256(resolution, root=tmp_path)

    override.write_text("# pinned for the simulator stack\nnumpy<3\n")
    assert baseline != requirements_sha256(resolution, root=tmp_path)


def test_override_that_is_not_utf8_is_a_configuration_error(
    make_component, make_catalog, tmp_path
):
    override = tmp_path / "robots/alpha/requirements/override.txt"
    override.parent.mkdir(parents=True)
    override.write_text("numpy<2\n", encoding="utf-8")
    robot = make_component(
        "robot-alpha", dependencies=["numpy>=2"], overrides=[override]
    )
    resolution = resolve(("robot-alpha",), make_catalog([robot]))

    # uv rejects a requirement file it cannot decode, so recording it as an
    # absent input would hide the problem behind a drift report.
    override.write_bytes(b"numpy\n\xff\n")

    with pytest.raises(InstallConfigError, match="not UTF-8"):
        requirements_inputs(resolution, root=tmp_path)


def test_requirements_hash_does_not_depend_on_how_the_checkout_is_named(
    make_component, make_catalog, tmp_path
):
    checkout = tmp_path / "checkout"
    override = checkout / "robots/alpha/requirements/override.txt"
    override.parent.mkdir(parents=True)
    override.write_text("numpy<2\n", encoding="utf-8")
    robot = make_component("robot-alpha", overrides=[override])
    resolution = resolve(("robot-alpha",), make_catalog([robot]))

    linked = tmp_path / "linked"
    linked.symlink_to(checkout, target_is_directory=True)

    assert requirements_sha256(resolution, root=linked) == requirements_sha256(
        resolution, root=checkout
    )


def test_requirements_hash_tracks_uv_settings_but_not_conflicts(
    make_component, make_catalog, tmp_path, write_toml
):
    robot = make_component("robot-alpha")
    resolution = resolve(("robot-alpha",), make_catalog([robot]))
    settings = """
        [project]
        name = "rpent"
        dependencies = []

        [tool.uv]
        prerelease = "allow"
        extra-build-dependencies = {}
        conflicts = [[{ extra = "a" }, { extra = "b" }]]
    """
    pyproject = write_toml("pyproject.toml", settings)

    baseline = requirements_sha256(resolution, root=tmp_path)
    assert requirements_inputs(resolution, root=tmp_path)["uv_settings"] == {
        "prerelease": "allow",
        "extra-build-dependencies": {},
    }

    pyproject.write_text(
        settings.replace('prerelease = "allow"', 'prerelease = "disallow"').strip()
        + "\n",
        encoding="utf-8",
    )
    assert baseline != requirements_sha256(resolution, root=tmp_path)

    # `conflicts` is generated from component manifests and only constrains
    # extra combinations, which `rpent-install` does not install from.
    pyproject.write_text(
        settings.replace(
            'conflicts = [[{ extra = "a" }, { extra = "b" }]]',
            'conflicts = [[{ extra = "a" }, { extra = "c" }]]',
        ).strip()
        + "\n",
        encoding="utf-8",
    )
    assert baseline == requirements_sha256(resolution, root=tmp_path)


def test_read_core_dependencies(write_toml, tmp_path):
    write_toml(
        "pyproject.toml",
        """
        [project]
        name = "alpha"
        dependencies = ["packaging", "PyYAML"]
        """,
    )

    assert read_core_dependencies(tmp_path) == ("packaging", "PyYAML")


@pytest.mark.parametrize(
    "text",
    [
        "",
        "[project]\nname = 'alpha'\n",
        "[project]\ndependencies = 'packaging'\n",
    ],
)
def test_read_core_dependencies_rejects_missing_table(write_toml, tmp_path, text):
    write_toml("pyproject.toml", text)

    with pytest.raises(InstallConfigError):
        read_core_dependencies(tmp_path)
