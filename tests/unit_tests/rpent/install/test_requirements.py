"""Requirements rendering is stable and hashes cover every install input."""

import pytest

from rpent.install.errors import InstallConfigError
from rpent.install.manifest import Selection
from rpent.install.requirements import (
    dependency_requirements_text,
    environment_dependencies,
    read_core_dependencies,
    render_requirements,
    requirements_inputs,
    requirements_sha256,
)
from rpent.install.resolve import resolve


@pytest.fixture
def resolution(make_component, make_profile, make_catalog):
    robot = make_component(
        "alpha",
        dependencies=["numpy>=2", "torch==2.7.0"],
        optional={"pro": ("extra-package",)},
    )
    external = make_component(
        "molmo",
        kind="capability",
        placements=("in-env", "external-env"),
        dependencies=["transformers>=4.57"],
    )
    profile = make_profile(
        "alpha",
        {
            "alpha": Selection(variant="pro"),
            "molmo": Selection(placement="external-env", env="molmo"),
        },
        dependencies=["pytest"],
    )
    catalog = make_catalog(components=[robot, external])
    return resolve(profile, catalog)


def test_render_requirements_groups_core_profile_and_components(resolution):
    text = render_requirements(
        resolution,
        "alpha",
        core_dependencies=("packaging", "PyYAML"),
    )

    assert text.splitlines()[:4] == [
        "# Generated by rpent-env from envs/alpha.toml.",
        "# Do not edit; change the profile or a component manifest and rerun",
        "# `rpent-env install alpha`.",
        "# environment: alpha",
    ]
    assert "# RPent core\nPyYAML\npackaging" in text
    assert "# profile alpha\npytest" in text
    assert "# component alpha (pro)" in text
    assert text.index("numpy>=2") < text.index("torch==2.7.0")
    assert "extra-package" in text


def test_external_environment_skips_core_and_profile(resolution):
    text = render_requirements(resolution, "molmo", core_dependencies=("packaging",))

    assert "# RPent core" not in text
    assert "# profile alpha" not in text
    assert "# component molmo" in text
    assert "transformers>=4.57" in text


def test_core_can_be_disabled(make_component, make_profile, make_catalog):
    profile = make_profile("molmo", {}, core=False)
    catalog = make_catalog(components=[])
    resolution = resolve(profile, catalog)

    assert (
        environment_dependencies(resolution, "molmo", core_dependencies=("packaging",))
        == ()
    )


def test_dependency_requirements_text_has_only_requirement_lines(resolution):
    text = dependency_requirements_text(
        resolution, "alpha", core_dependencies=("packaging",)
    )

    assert text.splitlines()[0] == "packaging"
    assert all(not line.startswith("#") for line in text.splitlines())
    assert "numpy>=2" in text
    assert "transformers" not in text


def test_requirements_hash_tracks_manifests_and_options(
    resolution, make_component, make_profile, make_catalog
):
    baseline = requirements_sha256(resolution, core_dependencies=("packaging",))

    assert baseline == requirements_sha256(resolution, core_dependencies=("packaging",))
    assert baseline != requirements_sha256(
        resolution, core_dependencies=("packaging",), include_dev=True
    )
    assert baseline != requirements_sha256(
        resolution, core_dependencies=("packaging", "pytest")
    )

    inputs = requirements_inputs(resolution, core_dependencies=("packaging",))
    assert inputs["profile"]["components"]["alpha"]["variant"] == "pro"
    assert inputs["profile"]["components"]["molmo"]["env"] == "molmo"
    assert inputs["core_dependencies"] == ["packaging"]


def test_read_core_dependencies(write_toml, tmp_path):
    write_toml(
        "pyproject.toml",
        """
        [project]
        name = "alpha"
        dependencies = ["packaging", "PyYAML"]
        """,
    )

    assert read_core_dependencies(tmp_path) == ("packaging", "PyYAML")


@pytest.mark.parametrize(
    "text",
    [
        "",
        "[project]\nname = 'alpha'\n",
        "[project]\ndependencies = 'packaging'\n",
    ],
)
def test_read_core_dependencies_rejects_missing_table(write_toml, tmp_path, text):
    write_toml("pyproject.toml", text)

    with pytest.raises(InstallConfigError):
        read_core_dependencies(tmp_path)
